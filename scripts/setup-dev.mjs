// Prepares a fresh clone for `npm run dev`. Runs automatically before it (npm "predev").
//   - frontend/dist must exist or `wrangler dev` refuses to start (wrangler.toml [assets]).
//   - .dev.vars is created with random secrets if missing, so nobody runs on a placeholder key.
//   - an existing .dev.vars keeps its values, except a placeholder JWT_SECRET (as copied from
//     .dev.vars.example), which is replaced with a random one.
//   - the local database gets any migrations it hasn't had yet, so pulling new code and running
//     `npm run dev` just works (otherwise every page fails with "no such table").
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { randomBytes, generateKeyPairSync } from 'node:crypto'

// A Web Push key pair for local testing (the browser only accepts push from localhost or https).
function vapidLines() {
  const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' })
  const pub = publicKey.export({ format: 'jwk' })
  const raw = Buffer.concat([Buffer.from([4]), Buffer.from(pub.x, 'base64url'), Buffer.from(pub.y, 'base64url')])
  return [`VAPID_PUBLIC_KEY=${raw.toString('base64url')}`, `VAPID_PRIVATE_KEY=${privateKey.export({ format: 'jwk' }).d}`]
}

mkdirSync('frontend/dist', { recursive: true })

if (!existsSync('.dev.vars')) {
  const email = process.env.BOOTSTRAP_ADMIN_EMAIL || 'mentor@example.org'
  writeFileSync('.dev.vars', [
    '# Local development only. Generated by scripts/setup-dev.mjs; never commit this file.',
    'ENVIRONMENT=development',
    'DEV_LOGIN=on',
    `JWT_SECRET=${randomBytes(32).toString('hex')}`,
    `BOOTSTRAP_ADMIN_EMAIL=${email}`,
    ...vapidLines(),
    '',
  ].join('\n'))
  console.log(`Created .dev.vars (first mentor: ${email}).`)
} else {
  let text = readFileSync('.dev.vars', 'utf8')
  const fixed = []
  if (/^JWT_SECRET=(change-me.*)?\s*$/m.test(text)) {
    text = text.replace(/^JWT_SECRET=.*$/m, `JWT_SECRET=${randomBytes(32).toString('hex')}`)
    fixed.push('JWT_SECRET')
  }
  if (!/^VAPID_PUBLIC_KEY=\S/m.test(text)) {
    text = `${text.replace(/^VAPID_(PUBLIC|PRIVATE)_KEY=.*\n?/gm, '').replace(/\n*$/, '\n')}${vapidLines().join('\n')}\n`
    fixed.push('push notification keys')
  }
  if (fixed.length) {
    writeFileSync('.dev.vars', text)
    console.log(`Filled in ${fixed.join(' and ')} in .dev.vars with random values.`)
  }
}

// Apply pending migrations to the local D1 database. Already-applied ones are skipped by wrangler.
const migrate = spawnSync('npx', ['wrangler', 'd1', 'migrations', 'apply', 'frc302-hub-db', '--local'], {
  stdio: ['ignore', 'pipe', 'pipe'], shell: process.platform === 'win32', env: { ...process.env, CI: '1' }, encoding: 'utf8',
})
if (migrate.status !== 0) {
  console.error(`${migrate.stdout || ''}${migrate.stderr || ''}`)
  console.error('\nCouldn’t update the local database (see above). Fix that, or run `npm run db:migrate:local` to see the error on its own.')
  process.exit(1)
}
const applied = [...new Set([...(migrate.stdout || '').matchAll(/(\d{4}_[\w-]+\.sql)\s*│\s*✅/g)].map((m) => m[1]))]
console.log(applied.length ? `Local database updated: ${applied.join(', ')}` : 'Local database is up to date.')
